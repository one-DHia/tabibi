CREATE OR REPLACE FUNCTION public.is_admin()
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
STABLE
AS $$
BEGIN
  RETURN COALESCE(
    (auth.jwt() ->> 'email') IN (
      'dhianouibet@gmail.com'   -- ← YOUR ADMIN EMAIL HERE
      -- Add more admins with comma: , 'second-admin@email.com'
    ),
    FALSE
  );
END;
$$;

-- Prevent anon/authenticated users from modifying this function
REVOKE ALL ON FUNCTION public.is_admin() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.is_admin() TO authenticated;
GRANT EXECUTE ON FUNCTION public.is_admin() TO anon;


