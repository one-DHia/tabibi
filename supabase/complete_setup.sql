-- ---- DOCTORS TABLE ----
CREATE TABLE IF NOT EXISTS public.doctors (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    name        TEXT NOT NULL CHECK (char_length(name) BETWEEN 1 AND 150),
    email       TEXT,
    specialty   TEXT NOT NULL CHECK (char_length(specialty) <= 100),
    image       TEXT,
    address     TEXT CHECK (char_length(address) <= 500),
    city        TEXT NOT NULL CHECK (char_length(city) <= 100),
    availability TEXT[],
    price       TEXT CHECK (char_length(price) <= 50),
    rating      NUMERIC DEFAULT 0 CHECK (rating >= 0 AND rating <= 5),
    reviews     INTEGER DEFAULT 0 CHECK (reviews >= 0),
    phone       TEXT CHECK (char_length(phone) <= 30),
    is_emergency BOOLEAN DEFAULT FALSE,
    is_verified  BOOLEAN DEFAULT FALSE,
    created_at  TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()),
    updated_at  TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW())
);

-- ---- REPORTS TABLE ----
CREATE TABLE IF NOT EXISTS public.reports (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doctor_id   BIGINT NOT NULL REFERENCES public.doctors(id) ON DELETE CASCADE,
    reporter_id UUID DEFAULT auth.uid() REFERENCES auth.users(id) ON DELETE SET NULL,
    reason      TEXT NOT NULL CHECK (char_length(reason) BETWEEN 1 AND 500),
    details     TEXT CHECK (char_length(details) <= 2000),
    status      TEXT DEFAULT 'pending' CHECK (status IN ('pending', 'reviewed', 'resolved', 'dismissed')),
    created_at  TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW())
);


