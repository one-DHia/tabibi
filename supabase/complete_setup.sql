-- SELECT: Anyone can browse doctors (public directory)
DROP POLICY IF EXISTS "doctors_select_public" ON public.doctors;
CREATE POLICY "doctors_select_public"
ON public.doctors FOR SELECT
USING (true);

-- INSERT: No direct insert allowed
-- Doctor profiles are created ONLY via the trigger (Section 5)
-- or by the admin via service_role key
-- Default RLS deny handles this — no policy = blocked
DROP POLICY IF EXISTS "doctors_insert_deny" ON public.doctors;

-- UPDATE: Doctor can update their OWN profile
DROP POLICY IF EXISTS "doctors_update_own" ON public.doctors;
CREATE POLICY "doctors_update_own"
ON public.doctors FOR UPDATE
USING (auth.uid() = user_id)
WITH CHECK (auth.uid() = user_id);

-- UPDATE: Admin can update ANY doctor (verify, modify, etc.)
DROP POLICY IF EXISTS "doctors_update_admin" ON public.doctors;
CREATE POLICY "doctors_update_admin"
ON public.doctors FOR UPDATE
USING (public.is_admin())
WITH CHECK (public.is_admin());

-- DELETE: Only admin can delete doctors
DROP POLICY IF EXISTS "doctors_delete_admin" ON public.doctors;
CREATE POLICY "doctors_delete_admin"
ON public.doctors FOR DELETE
USING (public.is_admin());


