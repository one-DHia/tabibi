-- ║        REPORTS — RLS POLICIES                ║
-- ╚══════════════════════════════════════════════╝

-- INSERT: Only authenticated users can submit reports
-- Also validates that reporter_id matches the current user
DROP POLICY IF EXISTS "reports_insert_auth" ON public.reports;
CREATE POLICY "reports_insert_auth"
ON public.reports FOR INSERT
WITH CHECK (
    auth.role() = 'authenticated'
    AND (reporter_id IS NULL OR reporter_id = auth.uid())
);

-- SELECT: Only admin can view all reports
DROP POLICY IF EXISTS "reports_select_admin" ON public.reports;
CREATE POLICY "reports_select_admin"
ON public.reports FOR SELECT
USING (public.is_admin());

-- SELECT: Users can see their OWN reports
DROP POLICY IF EXISTS "reports_select_own" ON public.reports;
CREATE POLICY "reports_select_own"
ON public.reports FOR SELECT
USING (auth.uid() = reporter_id);

-- UPDATE: Only admin can change report status
DROP POLICY IF EXISTS "reports_update_admin" ON public.reports;
CREATE POLICY "reports_update_admin"
ON public.reports FOR UPDATE
USING (public.is_admin())
WITH CHECK (public.is_admin());

-- DELETE: Only admin can delete reports
DROP POLICY IF EXISTS "reports_delete_admin" ON public.reports;
CREATE POLICY "reports_delete_admin"
ON public.reports FOR DELETE
USING (public.is_admin());


-- ============================================================
-- SECTION 5: TRIGGER — Auto-Create Doctor Profile on Signup
-- ============================================================
-- When a user signs up with role='doctor' in their metadata,
-- this trigger creates a doctor profile in the doctors table.
-- All input is validated and sanitized.

CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  _role     TEXT;
  _name     TEXT;
  _phone    TEXT;
  _specialty TEXT;
  _city     TEXT;
BEGIN
  -- Extract role from metadata (default to 'user')
  _role := LOWER(TRIM(COALESCE(new.raw_user_meta_data ->> 'role', 'user')));

  -- ⛔ SECURITY: Block admin role assignment via signup
  IF _role NOT IN ('user', 'doctor') THEN
    _role := 'user';
  END IF;

  -- Only create a doctor profile for doctor signups
  IF _role = 'doctor' THEN
    -- Sanitize name (max 150 chars)
    _name := TRIM(COALESCE(new.raw_user_meta_data ->> 'name', 'Docteur'));
    IF char_length(_name) > 150 THEN
      _name := substring(_name FROM 1 FOR 150);
    END IF;

    -- Sanitize phone (max 30 chars, digits and spaces only)
    _phone := LEFT(TRIM(COALESCE(new.raw_user_meta_data ->> 'phone', '')), 30);

    -- Sanitize specialty (max 100 chars)
    _specialty := LEFT(TRIM(COALESCE(new.raw_user_meta_data ->> 'specialty', 'general_practitioner')), 100);

    -- Sanitize city (max 100 chars)
    _city := LEFT(TRIM(COALESCE(new.raw_user_meta_data ->> 'wilaya', 'non spécifié')), 100);

    INSERT INTO public.doctors (
      user_id, email, name, phone, specialty, city,
      rating, reviews, is_verified
    ) VALUES (
      new.id,
      new.email,
      _name,
      _phone,
      _specialty,
      _city,
      0,      -- Rating starts at 0 (earned, not given)
      0,      -- No reviews yet
      FALSE   -- ⛔ NEVER auto-verify — admin validates manually
    );
  END IF;

  RETURN new;
END;
$$;

-- Create trigger on auth.users
DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();


-- ============================================================
-- SECTION 6: AUTO-UPDATE TIMESTAMPS
-- ============================================================
-- Automatically sets `updated_at` whenever a doctor row is modified.

CREATE OR REPLACE FUNCTION public.update_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS doctors_set_updated_at ON public.doctors;
CREATE TRIGGER doctors_set_updated_at
  BEFORE UPDATE ON public.doctors
  FOR EACH ROW EXECUTE FUNCTION public.update_updated_at();


